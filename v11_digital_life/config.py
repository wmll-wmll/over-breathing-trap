"""V11 全部超参数，集中管理。没有魔法数字散落在别处。

★ 单场设计（2026-10-18 修订）
----------------------------
最初版本里有一个「矩阵」层夹在中间（场 → 矩阵 → Transformer）。
那个层是 v10 的遗产，经核对是多余的：

  * 矩阵通道 0-2 只是「场的归一化读数」—— 多此一举，
    而且它除以自身最大值，把能量信息除没了（实测：100% 和 4% 能量下矩阵完全一样）；
  * 矩阵通道 3-8 是 Transformer 自己写、自己读的便签，
    **中间没有任何一步影响场或生死** —— 是死胡同。

所以现在：**全场只有一个状态，就是 NLSE 场 ψ。**
Transformer 每拍把 ψ 现场铺成输入张量，读完就扔，不持有第二份状态。
"""

from __future__ import annotations

from dataclasses import dataclass, field as dc_field

from . import physics


@dataclass
class FieldConfig:
    """NLSE 场的物理参数。场的能量 E = Σ|ψ|² 完全由场自己决定。"""

    grid: int = 128
    """场的空间分辨率（grid × grid）。不降采样。"""

    dt: float = 0.5
    """一个心跳的时间步长（秒）。2 Hz。"""

    hbar: float = 1.0
    mass: float = 1.0

    non_linearity: float = 2.0
    """g：非线性自相互作用强度。-g|ψ|²ψ 项。太小是白开水，太大会炸。"""

    dissipation: float = 0.010
    """γ：每步的能量衰减。

    ★ 这个值必须足够大，否则任务不成立。
      实测（200 步空跑、AGC 关闭）：

        dissipation   200步后能量   判定
        0.0015          74.1%      ❌ 什么都不写也能活 1080 步
        0.0080          20.2%      ❌ 卡在死亡线上
        0.0100          13.5%      ✅ 会死 —— 任务成立

    **这就是「活着」的代价。**"""

    noise_eta: float = 0.08
    """持久噪声幅度。让场永不静止。

    注意：噪声是**能量中性**的 —— 加完会归一化回原能量。
    否则噪声会持续泵入能量，耗散就失去意义。"""

    norm_target: float = 10000.0
    """当 grid=128 时的能量容量。**运行时由 physics.energy_capacity(m) 覆盖**。

    能量容量 ∝ 体重（= 格子数），所以长大后它跟着涨。
    128×128 → m=16,384 → E₀=10,000
    129×129 → m=16,641 → E₀=10,157
    """

    meta_k: float = physics.META_K
    """基础代谢系数：每拍从本地光强里吸取 `meta_k × light` 的能量。

    ★ 这是「光提供能量、距离越远获取越少」的物理实现。
      平衡点 E* = meta_k × light / γ（γ = dissipation = 0.01）。

      标定：走廊中心光强实测 ≈ 0.187，希望那里刚好打平（E* = 1.0×E₀）：
        meta_k × 0.187 / 0.01 = 10,000  →  meta_k ≈ 535

      于是位置第一次有了物理后果：
        太远（light 0.187）→ E* = 1.00×  → 刚打平，一动就亏，容易饿死
        合适（light 0.320）→ E* = 1.71×  → ★ 最优，能跑能活
        太近（light 0.70） → E* = 3.74×  → 撑死

      **设为 0 可关闭代谢**（回到「场自己只掉不涨」的旧行为）。"""

    breath_mode: bool = False
    """★ 实验 8：把「呼吸深度」交给网络决定。

    False = 旧行为（实验 1-7）：代谢吸收是常数 k_meta × light。
    True  = 新行为：吸收量 = breath_k × light × k − breath_c × k²，
            k 由第二趟（或呼吸干路）每 `breath_period` 拍输出一次。

    ★ 这是「多 Transformer 架构」这个问题的**前提**：
      在只有一个输出（力）的时候，「按功能拆模块」根本无从谈起。
      有了第二个功能，拆分才有可比较的对象。"""

    breath_k: float = physics.BREATH_K
    """呼吸线性项系数（吸得越深拿得越多）。"""

    breath_c: float = physics.BREATH_C
    """呼吸二次代价系数（吸得越深效率越低）。

    ★ 没有它的话「吸到底」就是平凡最优解，这一维动作学不到东西。
      它让最优深度 k* = breath_k × light / (2 × breath_c) 随光强变化。"""

    agc_rate: float = 0.0
    """自动增益控制。**默认 0（关闭）。**

    ★ 为什么必须关：AGC 是手写的能量恢复规则，绕过了 Transformer。
      实测（dissipation=0.010，200 步）：

        agc_rate=0.000 -> 13.5%  会死
        agc_rate=0.002 -> 21.4%  靠 AGC 活着   ← 已经是拐杖了
        agc_rate=0.010 -> 47.0%  靠 AGC 活着

      留着它，就等于承认「本体可以不经 Transformer 获得能量」。"""

    init_amp: float = 0.05
    """初始场的幅度（会先归一化到 norm_target）。"""

    write_cost: float = 0.15
    """★ 写入的能量代价系数（每单位 |Δ| 的 L1 代价）。

    为什么要这个：对 ψ 的随机写入，能量增益只有二次项 n²Δ²（恒正），
    所以「一直写满」就是平凡最优解，agent 学不到任何东西。

    代价要大于二次项增益，于是：
        随机写 → 净亏（二次增益 < 代价）
        对齐写 → 净赚（线性项 Σ2ψΔ 远大于代价）
    **任务变成：学会「顺着 ψ 的相位写」。**"""

    obs_channels: int = 3
    """给 Transformer 的输入张量通道数：[Re(ψ), Im(ψ), |ψ|²]。

    ★ 用**固定参考尺度**铺，不做自适应归一化 ——
      否则能量信息会被除掉（旧版本就是这么丢掉能量的）。"""


@dataclass
class InterfaceConfig:
    """两趟 Transformer 的尺寸。"""

    d_model: int = 64
    n_heads: int = 4
    n_layers_pass1: int = 2
    n_layers_pass2: int = 2

    patch: int = 1
    """**已废弃**：现在逐格 token（128×128 = 16,384 个），不再切 patch。
    保留这个字段只是为了让旧的分析脚本不至于直接报错。"""

    obs_dim: int = 7
    """世界观测矢量的维度 —— 它是唯一的额外 token。

    ★ 2026-10-18 修订：不再有「身体内感受」那一半。
      场的每个格子直接进 Transformer（16,384 个 token），
      场的幅度本身就体现了能量，不需要再单独喂一个标量。

      世界观测 8 维：[位置x, 位置z, 光强, 光强变化, 上拍动作×3, 时间]

    为什么仍然保留这一个 token：
      世界必须有个入口。如果输入**只有**场本身，那场就完全封闭，
      agent 在世界里怎么移动都不会影响任何东西 —— 闭环断掉。"""

    action_dim: int = 2
    """动作维度：三维速度。"""

    write_gain_max: float = 0.5
    """写场增益的上限（`write_gain` 被 clamp 到 [0, 这个值]）。

    ★ 这是「写场」这个杠杆的最大力量。
      0.5  → 每格 Δψ 最大 ±0.5，会让能量在一拍内变动 10% 的 E₀（太猛）
      0.05 → 最大变动约 1% 的 E₀/拍，接近耗散量级（温和）

    实测（实验 2/3）：write_gain = 0.5 时，写场头的任何微小参数变化
    都能让能量在 30 拍内冲过整条生存带 —— 这是「震荡发散」的直接原因。
    """

    dropout: float = 0.0

    # ── ★ 实验 8：多 Transformer 布局 ──────────────────────────────
    breath_dim: int = 1
    """呼吸动作的维度（1 个标量：呼吸深度 k）。"""

    split_pass2: bool = False
    """★ 核心控制变量：第二趟要不要拆成两条独立干路。

    False（臂 A / 臂 D）= 单干路：一套 pass2 表示，两个头（力、呼吸）共用。
    True （臂 B / 臂 C）= 双干路：pass2 给力，pass2_meta 给呼吸，互不干扰。

    ★ 这是本实验唯一的架构变量。两条干路的层数之和恒等于单干路的层数，
      所以「拆」和「不拆」的**参数量完全相同** —— 拆分的收益不能来自容量。"""

    n_layers_meta: int = 1
    """split_pass2=True 时，呼吸干路的层数。"""

    meta_pool: int = 1
    """★ 呼吸干路的空间分辨率（下采样倍数）。

    1 = 逐格（16,384 token）—— 臂 B，和力干路同分辨率，算力也相同。
    4 = 4×4 平均池化（1,024 token）—— 臂 C，呼吸干路只花 6% 的注意力算力。

    ★ 臂 C 才是「多 Transformer」这个想法真正有理论优势的地方：
      呼吸深度只依赖「这里有多亮」这一个全局量，不需要 16,384 个格子的细节。
      用高分辨率去算一个低维量是浪费。**拆开之后才允许两条干路用不同分辨率** ——
      单干路做不到，因为它们必须共享同一份 token 序列。"""

    # ── ★ 实验 9：主干网络用哪个架构家族 ──────────────────────────
    arch: str = "transformer"
    """`"transformer"`（逐格 token + 注意力）或 `"cnn"`（卷积分支）。

    ★ 为什么必须试一下 CNN：
      当前 Transformer 接口的参数量是 1,249,740，其中
        `pos`（可学习绝对位置编码）16,385 × 64 = 1,048,640  ← **占 83.9%**
      也就是说这个「Transformer」里有 84% 的参数是**一张绝对位置查表**。

      而任务是平移协变的：NLSE 动力学不区分哪个像素，输出是全局量
      （3 维力 / 1 个呼吸标量），位置信息已经由世界 token 单独给出。
      那张位置表学的是**用不上**的先验，还可能让模型「记住位置」而不是
      「学场的动力学」。

      CNN 反过来：3×3 感受野 ↔ 拉普拉斯邻域耦合；平移等变；O(n) 而非 O(n²)；
      下采样天然给出低分辨率分支。"""

    cnn_channels: tuple = (32, 64, 128)
    """CNN 每级的通道数。每一级都 stride=2，所以 3 级 → 128→64→32→16。"""

    cnn_blocks: int = 2
    """每级放几个卷积块（第 1 个带 stride=2，其余同分辨率）。"""

    cnn_breath_channels: int = 16
    """独立呼吸分支的通道数（两次 stride=4，输出 8×8）。
    算力只有主干的约 1/16 —— 这正是「呼吸只需要低分辨率」在卷积里的自然写法。"""

    pool_world_separate: bool = True
    """★ 实验 10 修正：Transformer 的动作头怎么池化 16,385 个 token。

    False（旧写法）= `h.mean(dim=1)` —— **把世界 token 和 16,384 个格子
                     一起平均**。世界 token 是唯一携带「这里多亮、我在哪」
                     的那个 token，却只占 1/16,385 的权重 ——
                     **光强信号被稀释成 0.006%，等于没了。**

    True （修正）  = 场单独平均池化，世界 token 单独取出，拼起来过一层投影。
                     多 2×d×d = 8,256 个参数（占 0.66%）。

    ★ 这个 bug 解释了实验 9 的一个核心现象：
      CNN 的动作头是 `cat(pool(场), 世界观测)` —— 世界观测**显式拼进去**，
      一点不稀释，所以 35k 参数的 CNN 三代就学会跟光走；
      而 1.2M 参数的 Transformer 学不会，因为它根本「看不见」光强。"""


@dataclass
class LifeConfig:
    """生死与训练。"""

    death_norm_frac: float = physics.LOWER
    """场能量低于 `E₀ × 这个比例` 就死 —— **低边（饿死）**。默认 0.20。"""

    max_norm_frac: float = physics.UPPER
    """场能量高于 `E₀ × 这个比例` 也死 —— **高边（撑死/失控）**。默认 3.00。

    ★ 为什么必须有高边：实测发现写入的能量增益 ∝ √E，而代价是常数，
      所以「把场撑大」变成了永远划算的策略 —— 场能量指数爆炸
      （实测两条命涨到 20× 和 27× 目标，然后永远不死）。

    → 加上高边之后，生命变成**一条带子里的稳态控制**。"""

    band_penalty: float = 0.0
    """可选：接近边界时的额外惩罚。默认 0（不加人为 shaping）。"""

    max_steps: int = 600
    """单个回合最多多少个心跳（300 秒）。"""

    lr: float = 3e-4
    gamma: float = 0.99
    entropy_coef: float = 0.01
    value_coef: float = 0.5

    init_log_std: float = -1.0
    """动作噪声的初始 log 标准差。-1.0 → σ≈0.37。

    ★ 不要用 0.0（σ=1）。v10 的教训：σ=1 而均值幅度只有 0.32 时，
      82% 的行为都是噪声，策略等于没学。"""

    write_coef: float = 5.0
    """写入损失的权重。

    ★ A2C 的策略梯度只覆盖「动作」的对数概率，第一趟的「写场」
      不经过动作分布 —— 它收不到任何策略梯度。
      实测：不加这一项时，训练越久死得越快（114 → 60 步）。

      所以写入走**可微目标**。目标有两种，由 `write_objective` 选：
        "speed"  —— 最大化速度能力（默认，推荐）
        "energy" —— 最大化 ΔE（旧的，会自爆，只用于对照）
        "none"   —— 不加写场损失（用于对照实验）"""

    write_objective: str = "speed"
    """写场头的训练目标。

    ★ 2026-10-20 修正：
      旧目标是 "energy"（最大化 ΔE），等于告诉写场头「拼命充能」。
      跨代学习实测：第 1 代活 90 拍 → 第 10 代活 22 拍，ΔE 从 +391
      涨到 +1216（写场强了 3.1 倍），每代都更快撞上 3.0 的上边界自爆。

      新目标 "speed" = 最大化 speed_scale(E)（速度能力）。
      它的峰值在 E ≈ 17480 = 1.75×E₀，离上边界 3.00 还有 1.25× 余量，
      而且最优点两侧都有梯度 —— 是一个真优化目标，不是单边推动。"""

    chunk: int = 8
    """每多少拍做一次反向传播。

    ★ 这个参数直接决定显存。
      逐格 token 后，**每拍的计算图约 276 MB**（两个 16,384-token 的 Transformer）。
      如果整回合（120~200 拍）攒着不 backward，会累积到 33 GB —— 实测爆显存。

      每 8 拍清一次：8 × 276 MB ≈ 2.2 GB，安全。
      代价是 A2C 变成 n 步回报（用 V(s_{t+K}) 做 bootstrap），这是标准做法。"""

    breath_period: int = physics.BREATH_PERIOD
    """★ 实验 8：呼吸决策的慢时钟（每多少拍重新决定一次呼吸深度）。

    移动决策是 1 拍一次的快时钟，呼吸是 10 拍一次的慢时钟。
    **两个功能在时间尺度上不同** —— 这是拆分有意义的第二个理由
    （第一个是分辨率，见 InterfaceConfig.meta_pool）。

    一个呼吸决策的影响要延续 breath_period 拍，所以它的优势函数
    用这 breath_period 拍的优势之和来估（见 Brain._a2c_update）。"""

    energy_reward_coef: float = 0.0
    """★ 实验 8：能量位置的稠密奖励系数（默认 0 = 不加 shaping）。

    为什么需要：纯存活奖励只在死亡那拍给 -1，而呼吸深度对存活的影响
    要经过「能量 → 几十拍后是否越界」才体现出来 —— 信用分配太远，
    呼吸头几乎学不动。加一项「离生存带中心有多近」的稠密奖励是标准做法。

    ★ 关键：所有臂用**同一个**奖励函数，所以它不会偏向任何一支。"""

    breath_objective: str = "policy"
    """★ 实验 10：呼吸头怎么训。

    "policy"      —— 只走策略梯度（实验 8/9 的做法，会出现「过度呼吸陷阱」）
    "homeostasis" —— **加一个可微目标**：让稳态能量停在生存带中心。
                     损失 = (E∞/E₀ − 1.6)²，其中 E∞ = gain·(1−γ)/γ。
    "both"        —— 两个都要（策略梯度 + 可微目标）

    ★ 为什么需要这个（实验 9 实测）
      57 次运行里 corr(末代 k, 存活) = −0.45；k<1.0 的平均活 300 拍，
      k>1.6 的只活 118 拍。而且同一个 2 层 Transformer 换个随机种子
      就从 k=0.61/350 拍 变成 k=1.96/155 拍。
      根因是呼吸这个慢时钟动作拿不到足够清晰的信用分配。

    ★ 这**不是**把答案喂进去：目标只说「停在哪」（生存带中心，
      由死亡规则自己定义的常数），没有说 k 该是多少 ——
      k 要多少完全取决于当前光强，光强仍然是网络自己从世界观测里看的。

    ★ 和当年修写场头是一个思路：写场头在实验 1-6 里同样拿不到策略梯度，
      解法就是给它一个可微目标（speed_scale 的峰）。"""

    breath_objective_coef: float = 1.0
    """上面那个可微目标的权重。"""

    breath_gamma_mode: str = "step"
    """★ 实验 12 修正：稳态公式里那个「每拍乘子」怎么算。

    `"step"`（默认，**正确**）= r_E = exp(−2·γ·dt) = 0.99005。
        为什么是 2γ：`NLSEField.step()` 里衰减的是**振幅**（`ψ *= exp(−γ·dt)`），
        而能量 E = Σ|ψ|²，所以能量乘子是振幅乘子的平方。
        于是 E∞ = gain/(1 − r_E) = 100.5·gain。
        **实测定标**（关噪声与代谢空跑 200 拍）：E(200)/E(0) = 0.135330 = exp(−2) ✓
    `"coef"`（实验 8-11 用的近似）= r = 1 − γ = 0.990。
        E∞ = gain·(1−γ)/γ = 99·gain，与真值 100.5 只差 **1.5%**。
        保留这个选项为了能逐位复现实验 8-11 的结果。

    ★ 自查记录（2026-10-24）
      这个字段的第一版把 `step` 写成了 exp(−γ·dt) = 0.99501，并据此断言
      「旧公式错 2.03 倍」。**那个断言是错的**：漏了「能量 ∝ 振幅²」这一步。
      旧公式 99 vs 真值 100.5，只差 1.5%，一直够用。
      教训：这类系数必须实测（空跑 N 拍看能量衰减），不能靠公式推导。
      详见 `实验报告/自查_物理自洽性.md`。"""

    breath_bound_mode: str = "useful"
    """★ 实验 F（第五轮）：呼吸上界的三种模式，用来把修复同时做的两件事分开。

    "useful" —— 上界 = k*(light)。既压到峰值以下，又随光强变化（实验 12 的配置）。
    "fixed"  —— 上界 = k*(light_ref)，light_ref 固定。只压峰值，不随光变。
    "excess" —— 上界 = min(BREATH_MAX, 2·k*(light))。随光变，但允许越过峰值。

    原来的 `breath_limit_useful` 布尔量仍然生效：为 False 时走全开区间
    `[BREATH_MIN, BREATH_MAX]`（2×2 的第四格，即 OLD_FULL）。"""

    breath_light_ref: float = 0.411
    """mode="fixed" 的参考光强。取世界 B 逐拍光强中位数（0.411）。"""

    breath_limit_useful: bool = True
    """★ 实验 12 修正：把呼吸动作**重参数化**到增益单调的那一段
    `[BREATH_MIN, k*(light)]`，而不是原来的整段 `[BREATH_MIN, BREATH_MAX]`。

    k*(light) = BREATH_K·light/(2·BREATH_C) = 1.125·light 是呼吸增益的
    最大值点。比它更深的呼吸**永远**更差（同样甚至更少的增益、更大的代价），
    所以 `(k*, BREATH_MAX]` 是一段**完全冗余**的动作区间：
    里面每一个深度都能被一个更浅的深度取代，拿到同样的增益。

    ★ 冗余本身不算错，但它让「稳态能量目标」有**两个解**（浅解 / 深解）。
      旧目标只约束 E∞、不区分两者 → 策略在对称分岔点上被噪声推向任一侧
      → 静态光下落在浅解看着没事，**光源一移动就翻到深解（k≈1.8），
      然后在暗处饿死**。这是实验 11 里所有带学习的臂震荡的直接原因。

    ★ 为什么用「重参数化」而不是「夹紧」
      `k = min(head, k*)` 会让钳位区梯度归零（`dk_eff/dz = 0`），
      网络既学不到「该减小 k」，也没有力量把自己推出来 —— 实测卡死。
      重参数化让 `dk/dz` 处处非零。

    False = 旧行为（动作空间 [0.05, 2.0] 全开），只用于 A/B 对照与复现实验 8-11。"""

    breath_account_move: bool = True
    """★ 实验 12 第三处修正：算稳态能量目标时，要不要扣掉**运动耗能**。

    能量预算的真实顺序是「先耗散 → 再呼吸补能 → 再扣走动开销」：

        E_{t+1} = E_t·r + gain_呼吸 − move_cost

    所以稳态是 `E∞ = (gain − move_cost)/(1−r)`。
    不扣 move_cost，目标就会把呼吸定得**太浅**：一个不停走动的个体，
    它呼吸拿到的增益要额外覆盖走路烧掉的能量，否则能量会往下滑。

    ★ 这是实验 12 里 1/3 种子仍然饿死的直接原因
      世界 A 里 move_cost ≈ 60 拍/能量，而呼吸最大增益只有 115 ——
      忽略这一项，目标算出来的 k 是 0.28（稳定在 0.16×E₀ 撑不住），
      扣掉之后应该顶到最大增益点 k*≈0.76。

    False = 旧行为（只看呼吸，不管运动），仅用于 A/B 对照。"""

    lr_breath: float = 0.01
    """★ 实验 10：呼吸头的**独立学习率**（用它自己的优化器）。

    ★ 为什么必须单独设：
      呼吸深度要从初值 1.50 走到 0.8 左右，也就是 z 从 +0.95 走到约 −0.5，
      跨度约 1.45。Adam 单个参数的每步位移大约就是 lr，
      而主干的学习率是 3e-4 —— 按这个速度要 4800 步才走完，
      但整个训练预算只有约 350 步。**实测：lr=3e-4 时 24 拍只把
      呼吸头偏置挪了 0.0009，等于没动。**

      给呼吸头 0.01（主干的 33 倍）：一个梯度步位移 ~0.01，
      145 步走完，不到半代就到位。

    ★ 为什么不设更大（第一版设了 0.02）：配合 sigmoid 映射时冲得太猛，
      直接撞到上下界并卡死（D 的 k=0.05、N1 的 k=2.0）。
      换成 softsign 映射 + 0.01 之后收敛稳。

    ★ 这也顺带解释了实验 9 里的现象：
      「同一个 2 层 Transformer 换种子就从 350 拍变成 155 拍」——
      呼吸头的有效学习能力本来就卡在悬崖边上，初始化稍微偏一点就走不动。"""

    clip_breath: float = 5.0
    """呼吸头自己的梯度裁剪阈值（和主干的 1.0 分开裁）。

    ★ 为什么分开：`clip_grad_norm_` 是按**全部参数的总范数**缩放的。
      主干的梯度范数很大，会把呼吸头那一点点梯度一起按比例压下去 ——
      这也是呼吸头学得慢的原因之一。两边分开裁，各自的尺度才保住。"""

    init_log_std_breath: float = -2.0
    """★ 实验 10：呼吸动作的探索噪声初值（−2.0 → z 空间 σ=0.135）。

    ★ 为什么必须比主干的 −1.0 小：
      呼吸是个**慢时钟标量**，每 10 拍才采一次，而且它直接决定能量收支。
      σ=0.37 换算到 k 是 ±0.14~0.15 —— 实测在 light=0.55 处，
      稳态最优 k≈0.62，而采样值会在 0.34~1.06 之间跳。
      k=1.06 时净增益只有 37（需要 162），能量必然下滑。
      **探索本身在杀死它。** σ=0.135 换算到 k 约 ±0.05，才是「微调」而不是「乱撞」。"""

    enable_write: bool = True
    """是否允许第一趟改写场（实验 7 起实测写场只会制造不稳定）。

    ★ 实验 8 设为 False：跳过第一趟（2 层 16,385 token 的 Transformer）——
      写场增益上限为 0 时它本来就什么也不写，跑它纯属浪费一半算力。
      跳过之后每个心跳的算力减半，同样的时间能多跑一倍的代数。

      注意这只影响**算力**，不影响架构对照：四支臂都不跑第一趟。"""


@dataclass
class EvolutionConfig:
    """★ 实验 11：种群 + 变异 + 选择 + 遗传。

    ★ 为什么这是「离数字生命最近」的那一步
    --------------------------------------
    实验 1-10 的全部机制，本质上都是**同一个灵魂反复投胎**：

        一个个体 → 学一辈子 → 死了 → 带着学到的网络权重重生

    这里面有「学习」，有「跨代累积」，但**没有进化**：
      · 没有种群（永远只有一个个体，没有并行的多样性）
      · 没有变异（后代的基因 = 父代的基因，只差学习改的那一点）
      · 没有选择（不管活得好不好，下一代都是它）
      · 没有可遗传的差异（个体之间不存在「谁的天赋更好」）

    于是「适应」这件事从来没有被**选择**过 —— 只有一个人在黑暗里摸索。
    生物界的智能不是这样长出来的：它是**大量变体 + 残酷筛选 + 可遗传**
    三件事同时存在的结果。

    本模块把这三件事补上。
    """

    population: int = 8
    """种群大小。每个个体有自己的基因组（= 网络权重），各自过完一生。"""

    generations: int = 15
    """跑多少代。"""

    mutation_rate: float = 0.05
    """★ 变异强度（相对量）。

    每个参数张量的变异标准差 = `mutation_rate × 该张量的 RMS`。

    ★ 为什么用**相对**而不是绝对 σ
      网络里不同参数的尺度差几个数量级：卷积核权重 RMS ≈ 0.1，
      而呼吸头的 bias ≈ 0.95（它被显式初始化成 BREATH_INIT_Z）。
      用同一个绝对 σ 的话，要么把卷积炸掉，要么对 bias 等于没变异。
      按张量自己的 RMS 定标 → 每个张量被扰动的**相对幅度**一致。

    ★ 为什么不能太小 / 太大
      太小（1e-3）→ 十代下来基因几乎没动，选择没有原料；
      太大（0.5）→ 后代变成随机网络，父代学到的结构被冲掉，
                  进化退化成「每代重新随机初始化」。
      0.05 的意思是「每代每个参数动 5%」，这是神经进化里的常用量级。"""

    mutation_floor: float = 1e-5
    """变异标准差的下限，防止全零张量永远不变异。"""

    n_parents: int = 2
    """每代让前几名繁殖。2 = 精英双亲。"""

    elitism: int = 1
    """原样保留几个最优个体（不复制、不变异）。防止已经找到的好解被变异毁掉。"""

    selection: str = "fitness"
    """`"fitness"` = 按适应度选父母；`"random"` = **随机选**（对照组）。

    ★ 为什么必须有 random 这一支
      如果只跑「按适应度选」并看到适应度上升，那可能是**任何**原因造成的：
      变异本身、寿命噪声、或者干脆是随机漂变。
      随机选择对照把「选择」这个变量单独摘出来：
      同样的种群、同样的变异、同样的世界，只把「谁当父母」换成掷骰子。
      **只有这一支不涨，才能说上涨是选择带来的。**"""

    inheritance: str = "lamarckian"
    """后天学到的权重能不能遗传。

    `"lamarckian"` = 能。后代继承父代**死前学会的**网络（实验 1-10 的做法）。
    `"darwinian"`  = 不能。后代只继承父代**出生时**的基因，学习成果随死亡消失。

    ★ 这个开关决定实验要回答哪个问题
      · 拉马克式：进化 + 跨代学习，和实验 10 的基线只差「种群/变异/选择」
      · 达尔文式：纯粹的进化。学习不遗传 → 每一代都必须重新学，
        于是被选择的是「出生时有多好」和「学得有多快」——
        这正是生物界的样子，也是「先天 vs 后天」这个问题的实验形式。"""

    inherit_optimizer: bool = False
    """后代的 Adam 动量要不要继承。

    ★ 默认 False：动量是**个体一生的记忆**，不是基因。
      达尔文式遗传里它必须清空，否则等于把学习成果偷偷传下去。
      拉马克式（单谱系基线）保留它，和实验 10 完全一致。"""


@dataclass
class Config:
    field: FieldConfig = dc_field(default_factory=FieldConfig)
    interface: InterfaceConfig = dc_field(default_factory=InterfaceConfig)
    life: LifeConfig = dc_field(default_factory=LifeConfig)
    evolution: EvolutionConfig = dc_field(default_factory=EvolutionConfig)

    seed: int = 0
    device: str = ""
    """空字符串 = 自动（有 CUDA 就用 CUDA）。

    ★ 逐格 token 后一个心跳有 16,384 个 token，CPU 上太慢（每次前向数秒）。
      有显卡时必须用显卡。"""

    def validate(self) -> None:
        assert 0.0 < self.life.death_norm_frac < self.life.max_norm_frac, \
            "死亡带必须满足 0 < 低边 < 高边"
        assert self.field.dissipation > 0, "必须耗散，否则没有求生压力"
        assert self.interface.obs_dim > 0, "世界观测至少 1 维"


DEFAULT = Config()
